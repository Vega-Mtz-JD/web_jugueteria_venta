-- Pedidos, entrega y pagos con QR (spec §5.4).
-- Los pedidos solo cambian a través de las funciones de 20261019000002_pedidos_rpc.sql:
-- el navegador nunca inserta ni actualiza `orders` directamente.

create type public.order_status as enum (
  'esperando_pago', 'en_revision', 'pagado', 'enviado', 'listo_para_recoger',
  'entregado', 'rechazado', 'cancelado', 'reembolsado'
);
create type public.delivery_method as enum ('recojo', 'envio_ciudad', 'encomienda');
create type public.zone_mode as enum ('domicilio', 'punto');

-- Tarifas de envío dentro de La Paz -----------------------------------------
alter table public.store_settings
  add column delivery_fee_home_cents int not null default 1500 check (delivery_fee_home_cents >= 0),
  add column delivery_fee_meeting_cents int not null default 0 check (delivery_fee_meeting_cents >= 0);

-- Zonas, puntos de encuentro y billeteras --------------------------------------
create table public.delivery_zones (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  mode public.zone_mode not null,
  is_active boolean not null default true,
  sort_order int not null default 0
);

create table public.meeting_points (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  reference text,
  is_active boolean not null default true,
  sort_order int not null default 0
);

create table public.payment_methods (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  qr_path text not null,
  account_holder text,
  is_active boolean not null default true,
  sort_order int not null default 0
);

alter table public.delivery_zones enable row level security;
alter table public.meeting_points enable row level security;
alter table public.payment_methods enable row level security;

create policy "zonas: lectura pública de activas" on public.delivery_zones
  for select to anon, authenticated using (is_active or (select public.is_admin()));
create policy "zonas: admin gestiona" on public.delivery_zones
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "puntos: lectura pública de activos" on public.meeting_points
  for select to anon, authenticated using (is_active or (select public.is_admin()));
create policy "puntos: admin gestiona" on public.meeting_points
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "billeteras: lectura pública de activas" on public.payment_methods
  for select to anon, authenticated using (is_active or (select public.is_admin()));
create policy "billeteras: admin gestiona" on public.payment_methods
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- Pedidos -------------------------------------------------------------------------
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  number int generated by default as identity unique,
  request_id uuid not null unique,
  customer_id uuid not null references public.profiles (id) on delete restrict,
  status public.order_status not null default 'esperando_pago',
  delivery_method public.delivery_method not null,
  zone_id uuid references public.delivery_zones (id),
  zone_mode public.zone_mode,
  address text,
  address_reference text,
  meeting_point_id uuid references public.meeting_points (id),
  meeting_point_custom text,
  recipient_name text not null,
  recipient_ci text,
  phone text not null,
  department text,
  city text,
  invoice_requested boolean not null default false,
  invoice_nit text,
  invoice_name text,
  subtotal_cents int not null check (subtotal_cents >= 0),
  delivery_fee_cents int not null check (delivery_fee_cents >= 0),
  total_cents int not null,
  rejection_reason text,
  shipping_agency text,
  tracking_code text,
  created_at timestamptz not null default now(),
  submitted_at timestamptz,
  status_changed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_total_check check (total_cents = subtotal_cents + delivery_fee_cents),
  constraint orders_invoice_check check (not invoice_requested or (invoice_nit is not null and invoice_name is not null))
);

create index orders_customer_id_idx on public.orders (customer_id, created_at desc);
create index orders_status_idx on public.orders (status, status_changed_at);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id uuid not null references public.products (id) on delete restrict,
  product_name text not null,
  unit_price_cents int not null check (unit_price_cents >= 0),
  quantity int not null check (quantity between 1 and 20)
);
create index order_items_order_id_idx on public.order_items (order_id);

create table public.order_events (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  from_status public.order_status,
  to_status public.order_status not null,
  actor text not null check (actor in ('cliente', 'admin', 'sistema')),
  note text,
  created_at timestamptz not null default now()
);
create index order_events_order_id_idx on public.order_events (order_id, created_at);

create table public.payment_proofs (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  path text not null unique,
  created_at timestamptz not null default now()
);
create index payment_proofs_order_id_idx on public.payment_proofs (order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_events enable row level security;
alter table public.payment_proofs enable row level security;

-- El cliente solo lee lo suyo; los cambios pasan por las funciones RPC.
create policy "pedidos: el cliente ve los suyos, admin todos" on public.orders
  for select to authenticated using (customer_id = (select auth.uid()) or (select public.is_admin()));
create policy "pedidos: admin edita" on public.orders
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

create policy "items: del dueño del pedido o admin" on public.order_items
  for select to authenticated using (exists (
    select 1 from public.orders o where o.id = order_id and (o.customer_id = (select auth.uid()) or (select public.is_admin()))
  ));
create policy "eventos: del dueño del pedido o admin" on public.order_events
  for select to authenticated using (exists (
    select 1 from public.orders o where o.id = order_id and (o.customer_id = (select auth.uid()) or (select public.is_admin()))
  ));
create policy "capturas: del dueño del pedido o admin" on public.payment_proofs
  for select to authenticated using (exists (
    select 1 from public.orders o where o.id = order_id and (o.customer_id = (select auth.uid()) or (select public.is_admin()))
  ));

revoke insert, update, delete on public.orders, public.order_items, public.order_events, public.payment_proofs from anon;
revoke insert, delete on public.orders, public.order_items, public.order_events, public.payment_proofs from authenticated;

create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

