values ('store-assets', 'store-assets', true, 5242880, array['image/*'])
on conflict (id) do nothing;

-- Ruta de una captura: <user_id>/<order_id>/<archivo>
create policy "capturas: el cliente sube a su pedido abierto" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'payment-proofs'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and exists (
      select 1 from public.orders o
      where o.id::text = (storage.foldername(name))[2]
        and o.customer_id = (select auth.uid())
        and o.status in ('esperando_pago', 'rechazado')
    )
  );
create policy "capturas: el cliente lee las suyas, admin todas" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'payment-proofs'
    and ((storage.foldername(name))[1] = (select auth.uid())::text or (select public.is_admin()))
  );
create policy "recursos de la tienda: admin sube" on storage.objects
  for insert to authenticated with check (bucket_id = 'store-assets' and (select public.is_admin()));
create policy "recursos de la tienda: admin edita" on storage.objects
  for update to authenticated using (bucket_id = 'store-assets' and (select public.is_admin()));
create policy "recursos de la tienda: admin borra" on storage.objects
  for delete to authenticated using (bucket_id = 'store-assets' and (select public.is_admin()));

